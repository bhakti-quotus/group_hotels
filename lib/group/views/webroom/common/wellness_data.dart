/// All unique categories derived from the data
List<String> get wellnessCategories {
  final cats =
      wellnessItems.map((e) => e['category'] as String).toSet().toList();
  cats.sort();
  return cats;
}

/// Subcategories for a given category
List<String> subcategoriesFor(String category) {
  final subs = wellnessItems
      .where((e) => e['category'] == category)
      .map((e) => e['subcategory'] as String)
      .toSet()
      .toList();
  subs.sort();
  return subs;
}